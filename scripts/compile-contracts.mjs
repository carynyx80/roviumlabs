// Compiles contracts with Hardhat and writes the ABI + bytecode used by the web app.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

execSync("npx hardhat compile --config hardhat.config.cjs", { stdio: "inherit" });
const art = JSON.parse(
  readFileSync(".hardhat/artifacts/contracts/RoviumAgentToken.sol/RoviumAgentToken.json", "utf8"),
);
mkdirSync("src/lib/chain/artifacts", { recursive: true });
writeFileSync(
  "src/lib/chain/artifacts/RoviumAgentToken.ts",
  `// Generated by scripts/compile-contracts.mjs — do not edit.\n// Source: contracts/RoviumAgentToken.sol (solc 0.8.28, optimizer 200 runs)\n` +
    `export const roviumAgentTokenAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n` +
    `export const roviumAgentTokenBytecode = "${art.bytecode}" as const;\n`,
);
console.log("wrote src/lib/chain/artifacts/RoviumAgentToken.ts");
